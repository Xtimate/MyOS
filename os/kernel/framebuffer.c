static void dbg_serial_print(const char *s) {
    while (*s) {
        __asm__ volatile ("outb %0, $0x3F8" : : "a"(*s));
        s++;
    }
}

static void dbg_serial_hex(unsigned int n) {
    char buf[9]; buf[8] = 0;
    for (int i = 7; i >= 0; i--) {
        int x = n & 0xF;
        buf[i] = x < 10 ? '0'+x : 'a'+x-10;
        n >>= 4;
    }
    dbg_serial_print(buf);
}
void fb_init(unsigned char *addr, unsigned int width, unsigned int height, unsigned int pitch, unsigned int bpp) {
    fb_addr = addr;
    fb_width = width;
    fb_height = height;
    fb_pitch = pitch;
    fb_bpp = bpp;
}

void fb_put_pixel(unsigned int x, unsigned int y, unsigned int color) {
    if (x >= fb_width || y >= fb_height) return;
    unsigned int *pixel = (unsigned int *)(fb_addr + y * fb_pitch + x * (fb_bpp / 8));
    *pixel = color;
}

void fb_fill_rect(unsigned int x, unsigned int y, unsigned int w, unsigned int h, unsigned int color) {
    for (unsigned int row = y; row < y + h; row++)
        for (unsigned int col = x; col < x + w; col++)
            fb_put_pixel(col, row, color);
}

void fb_clear(unsigned int color) {
    fb_fill_rect(0, 0, fb_width, fb_height, color);
}

void fb_draw_char(unsigned int x, unsigned int y, char c, unsigned int fg, unsigned int bg) {
    const unsigned char *glyph = font[(unsigned char)c];
    for (int row = 0; row < 16; row++) {
        unsigned char bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col))
                fb_put_pixel(x + col, y + row, fg);
            else
                fb_put_pixel(x + col, y + row, bg);
        }
    }
}

void fb_draw_string(unsigned int x, unsigned int y, const char *str, unsigned int fg, unsigned int bg) {
    while (*str) {
        fb_draw_char(x, y, *str, fg, bg);
        x += 8;
        str++;
    }
}

static void fb_scroll() {
    cursor_notify_dirty();

    unsigned int row_bytes = fb_pitch * 16;
    unsigned char *dst = fb_addr;
    unsigned char *src = fb_addr + row_bytes;
    unsigned int copy_size = row_bytes * (TERM_ROWS - 1);

    for (unsigned int i = 0; i < copy_size; i++)
        dst[i] = src[i];

    for (unsigned int y = fb_height - 16; y < fb_height; y++)
        for (unsigned int x = 0; x < fb_width; x++)
            fb_put_pixel(x, y, TERM_BG);
}

void fb_terminal_init(void) {
    term_x = 0;
    term_y = 0;
    fb_clear(TERM_BG);
}

void fb_terminal_putchar(char c) {
    if (esc_state == 0 && c == 27) { // ESC
        esc_state = 1;
        return;
    }
     if (esc_state == 1) {
          if (c == '[') {
            esc_state = 2;
         } else {
               esc_state = 0; // not a CSI sequence, just drop it
         }
           return;
       }
       if (esc_state == 2) {
        if (c >= '0' && c <= '9') {
            return; // parameter digit, keep collecting
        }
        if (c == ';') {
            return; // parameter separator, keep collecting
        }
        // final byte of the sequence
        esc_state = 0;
        if (c == 'K') {
            dbg_serial_print("erase-line: term_x=");
            dbg_serial_hex(term_x);
            dbg_serial_print(" term_y=");
            dbg_serial_hex(term_y);
            dbg_serial_print(" TERM_COLS=");
            dbg_serial_hex(TERM_COLS);
            dbg_serial_print("\n");
            // erase from cursor to end of current line
            for (int x = term_x; x < TERM_COLS; x++) {
                fb_draw_char(x * 8, term_y * 16, ' ', TERM_FG, TERM_BG);
            }
        }
        // any other final letter (cursor movement etc.) is silently swallowed for now
        return;
    }

    if (c == '\n') {
        term_x = 0;
        term_y++;
        if (term_y >= TERM_ROWS) {
            fb_scroll();
            term_y = TERM_ROWS - 1;
        }

        return;
    }

    if (c == '\b') {
        if (term_x > 0) {
            term_x--;
            fb_draw_char(term_x * 8, term_y * 16, ' ', TERM_FG, TERM_BG);
        }
        return;
    }

    if (term_x >= TERM_COLS || term_y >=TERM_ROWS) return;

    fb_draw_char(term_x * 8, term_y * 16, c, TERM_FG, TERM_BG);
    term_x++;
    if (term_x >= TERM_COLS) {
        term_x = 0;
        term_y++;
        if (term_y >= TERM_ROWS) {
            fb_scroll();
            term_y = TERM_ROWS - 1;
        }
    }
}

void fb_terminal_write(const char *str) {
    while (*str)
        fb_terminal_putchar(*str++);
}

void fb_terminal_print(const char *str) {
    while (*str)
        fb_terminal_putchar(*str++);
}

void fb_terminal_print_num(unsigned int n) {
    char buf[12];
    int i = 10;
    buf[11] = 0;
    if (n == 0) { fb_terminal_putchar('0'); return; }
    while (n && i >= 0) {
        buf[i--] = '0' + (n % 10);
        n /= 10;
    }
    fb_terminal_print(&buf[i + 1]);
}

unsigned int fb_get_pixel(unsigned int x, unsigned int y) {
    if (x >= fb_width || y >= fb_height) return 0;
    unsigned int *pixel = (unsigned int *)(fb_addr + y * fb_pitch + x * (fb_bpp / 8));
    return *pixel;
}
